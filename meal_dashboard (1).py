"""**2.2: DataQualityChecker Class**

This class will check for missing values, invalid entries, duplicate records among other data quality issues
"""

class DataQualityChecker:
    """Check MEAL indicator datasets for common data quality issues."""

    REQUIRED_COLUMNS = [
        "indicator_name",
        "reporting_period",
        "quarterly_target",
        "actual",
        "annual_target"
    ]

    VALID_PERIODS = ["Q1", "Q2", "Q3", "Q4"]

    def __init__(self, data):
        """Initialise the checker with a copy of the supplied dataset."""
        if not isinstance(data, pd.DataFrame):
            raise TypeError("Input data must be a pandas DataFrame.")

        self.data = data.copy()
        self.issues = pd.DataFrame()

    def check_columns(self):
        """Check that all required columns are present."""
        missing_columns = [
            column for column in self.REQUIRED_COLUMNS
            if column not in self.data.columns
        ]

        if missing_columns:
            raise ValueError(
                f"Missing required columns: {missing_columns}"
            )

        return True

    def check_missing_values(self):
        """Identify missing values in required fields."""
        self.check_columns()

        missing = self.data[
            self.data[self.REQUIRED_COLUMNS].isna().any(axis=1)
        ].copy()

        if not missing.empty:
            missing["issue"] = "Missing required value"

        return missing

    def check_duplicates(self):
        """Identify repeated indicator-period records."""
        self.check_columns()

        duplicates = self.data[
            self.data.duplicated(
                subset=["indicator_name", "reporting_period"],
                keep=False
            )
        ].copy()

        if not duplicates.empty:
            duplicates["issue"] = "Duplicate indicator-period record"

        return duplicates

    def check_invalid_values(self):
        """Identify invalid periods and invalid numerical values."""
        self.check_columns()
        findings = []

        for index, row in self.data.iterrows():
            period = row["reporting_period"]

            if pd.notna(period) and period not in self.VALID_PERIODS:
                findings.append({
                    "row_index": index,
                    "indicator_name": row["indicator_name"],
                    "reporting_period": period,
                    "issue": "Invalid reporting period"
                })

            for column in [
                "quarterly_target", "actual", "annual_target"
            ]:
                value = row[column]

                if pd.isna(value):
                    continue

                if isinstance(value, (bool, np.bool_)) or not isinstance(
                    value, (int, float, np.integer, np.floating)
                ):
                    findings.append({
                        "row_index": index,
                        "indicator_name": row["indicator_name"],
                        "reporting_period": period,
                        "issue": f"Non-numeric value in {column}"
                    })
                    continue

                if not np.isfinite(value):
                    findings.append({
                        "row_index": index,
                        "indicator_name": row["indicator_name"],
                        "reporting_period": period,
                        "issue": f"Non-finite value in {column}"
                    })
                    continue

                if value < 0:
                    findings.append({
                        "row_index": index,
                        "indicator_name": row["indicator_name"],
                        "reporting_period": period,
                        "issue": f"Negative value in {column}"
                    })

                if column in [
                    "quarterly_target", "annual_target"
                ] and value == 0:
                    findings.append({
                        "row_index": index,
                        "indicator_name": row["indicator_name"],
                        "reporting_period": period,
                        "issue": f"Zero value in {column}"
                    })

        return pd.DataFrame(findings)

    def check_annual_target_consistency(self):
        """Identify indicators with inconsistent annual targets."""
        self.check_columns()

        valid_targets = self.data.dropna(
            subset=["indicator_name", "annual_target"]
        )

        target_counts = valid_targets.groupby(
            "indicator_name"
        )["annual_target"].nunique()

        inconsistent_names = target_counts[
            target_counts > 1
        ].index

        inconsistent = valid_targets[
            valid_targets["indicator_name"].isin(inconsistent_names)
        ].copy()

        if not inconsistent.empty:
            inconsistent["issue"] = "Inconsistent annual target"

        return inconsistent

    def run_all_checks(self):
        """Run all data quality checks and return a summary."""
        self.check_columns()

        missing = self.check_missing_values()
        duplicates = self.check_duplicates()
        invalid = self.check_invalid_values()
        inconsistent = self.check_annual_target_consistency()

        self.issues = pd.concat(
            [
                missing,
                duplicates,
                invalid,
                inconsistent
            ],
            ignore_index=True,
            sort=False
        )

        return {
            "records_checked": len(self.data),
            "missing_value_rows": len(missing),
            "duplicate_rows": len(duplicates),
            "invalid_value_issues": len(invalid),
            "inconsistent_target_rows": len(inconsistent),
            "total_issues": len(self.issues),
            "issues": self.issues
        }

