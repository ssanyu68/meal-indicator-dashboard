class Indicator:
    """Represent a MEAL indicator for a reporting period."""

    def __init__(
        self,
        indicator_name,
        reporting_period,
        target,
        actual,
        annual_target
    ):
        """Initialise an indicator with its target and actual values."""

        # Validate the indicator name
        if not isinstance(indicator_name, str) or not indicator_name.strip():
            raise ValueError("Indicator name must not be empty.")

        # Validate the reporting period
        valid_periods = ["Q1", "Q2", "Q3", "Q4"]

        if reporting_period not in valid_periods:
            raise ValueError("Reporting period must be Q1, Q2, Q3 or Q4.")

        # Validate numerical values
        for field_name, value in {
            "target": target,
            "actual": actual,
            "annual_target": annual_target
        }.items():
            if isinstance(value, (bool, np.bool_)) or not isinstance(
                value, (int, float, np.integer, np.floating)
            ):
                raise TypeError(f"{field_name} must be numeric.")

            if not np.isfinite(value):
                raise ValueError(f"{field_name} must be finite.")

            if value < 0:
                raise ValueError(f"{field_name} cannot be negative.")

        if target <= 0:
            raise ValueError("Quarterly target must be greater than zero.")

        if annual_target <= 0:
            raise ValueError("Annual target must be greater than zero.")

        # Store the validated data
        self._indicator_name = indicator_name.strip()
        self._reporting_period = reporting_period
        self._target = float(target)
        self._actual = float(actual)
        self._annual_target = float(annual_target)

    @property
    def indicator_name(self):
        """Return the indicator name."""
        return self._indicator_name

    @property
    def reporting_period(self):
        """Return the reporting period."""
        return self._reporting_period

    @property
    def target(self):
        """Return the quarterly target."""
        return self._target

    @property
    def actual(self):
        """Return the actual achievement."""
        return self._actual

    @property
    def annual_target(self):
        """Return the annual target."""
        return self._annual_target

    def calculate_achievement(self):
        """Calculate achievement as a percentage of the quarterly target."""
        return (self.actual / self.target) * 100

    def calculate_performance_gap(self):
        """Calculate the difference between target and actual achievement."""
        return self.target - self.actual

    def to_dict(self):
        """Return indicator details as a dictionary."""
        return {
            "indicator_name": self.indicator_name,
            "reporting_period": self.reporting_period,
            "quarterly_target": self.target,
            "actual": self.actual,
            "annual_target": self.annual_target,
            "achievement_pct": self.calculate_achievement(),
            "performance_gap": self.calculate_performance_gap()
        }

