"""**2.4: Creating the ReportGeneratorClass**

This class prepares analysis findings for reporting. It shows quarterly and annual performance, any data quality issues and indicators requiring follow-up
"""

class ReportGenerator:
    """Generate summary reports from MEAL performance and data-quality results."""

    def __init__(self, performance_analyzer, data_quality_checker):
        self.performance_analyzer = performance_analyzer
        self.data_quality_checker = data_quality_checker

    def generate_quarterly_report(self):
        """Return quarterly indicator performance results."""
        return self.performance_analyzer.analyze_quarterly_performance()

    def generate_annual_report(self):
        """Return annual indicator performance results."""
        return self.performance_analyzer.analyze_annual_performance()

    def generate_follow_up_report(self):
        """Return indicators needing improvement or classified off track."""
        return self.performance_analyzer.get_indicators_requiring_attention()

    def generate_data_quality_report(self):
        """Return data-quality findings and summary."""
        return self.data_quality_checker.run_all_checks()

    def generate_overall_summary(self):
        """Return key figures for a high-level MEAL performance report."""

        quarterly = self.performance_analyzer.analyze_quarterly_performance()
        annual = self.performance_analyzer.analyze_annual_performance()
        quality_summary = self.data_quality_checker.run_all_checks()

        summary = {
            "Total quarterly records analysed": len(quarterly),
            "Unique indicators": quarterly["indicator_name"].nunique(),
            "Annual indicators complete": int(
                (annual["data_status"] == "Complete").sum()
            ),
            "Annual indicators requiring review": int(
                (annual["data_status"] == "Review Required").sum()
            ),
            "Quarterly records On Track": int(
                (quarterly["performance_status"] == "On Track").sum()
            ),
            "Quarterly records Needs Improvement": int(
                (quarterly["performance_status"] == "Needs Improvement").sum()
            ),
            "Quarterly records Off Track": int(
                (quarterly["performance_status"] == "Off Track").sum()
            )
        }

        return pd.DataFrame(
            list(summary.items()),
            columns=["Measure", "Result"]
        )

